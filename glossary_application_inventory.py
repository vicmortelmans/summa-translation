# Suffixes that start with a vowel trigger Dutch spelling changes in the stem
# (daad -> daden, geheel -> gehele, oorzaak -> oorzaken).
VOWEL_SUFFIXES = (
    "e", "en", "er", "ere", "st", "ste", "de", "den", "te", "ten", "end",
    "ende", "ing",
)

# Function words are matched literally in multi-word definitions.
STOPWORDS = {
    "het", "de", "een", "van", "in", "te", "zich", "op", "aan", "met", "tot",
    "voor", "bij", "als", "dat", "die", "dit", "der", "des", "niet", "om",
    "uit", "over", "onder", "tegen", "naar", "zonder", "er",
}

ARTICLE_PREFIXES = ("de", "het", "die", "dat")


@lru_cache(maxsize=None)
def fold(word: str) -> str:
    """Lower-case a word and strip diacritics for comparison."""
    decomposed = unicodedata.normalize("NFD", word.lower())
    return "".join(char for char in decomposed
                   if unicodedata.category(char) != "Mn")


@lru_cache(maxsize=None)
def variants(term: str) -> frozenset[str]:
    """Return the accepted surface variants of a definition term."""
    term = fold(term.strip())
    out = {term}
    out.update(term + suffix for suffix in SUFFIXES)
    out.update(IRREGULAR.get(term, set()))

    # Dutch spelling: a doubled long vowel becomes single before a vowel suffix.
    for long_vowel in ("aa", "ee", "oo", "uu"):
        if long_vowel in term:
            collapsed = term.replace(long_vowel, long_vowel[0])
            out.update(collapsed + suffix for suffix in VOWEL_SUFFIXES)

    if term.endswith("heid") and len(term) > 5:
        root = term[:-4]
        out.update({root, root + "e", root + "en", root + "er", root + "ere",
                    root + "st", root + "ste", root + "heden"})
    if term.endswith("heden") and len(term) > 6:
        root = term[:-5]
        out.update({root, root + "e", root + "en"})
    if term.endswith("ing") and len(term) > 4:
        root = term[:-3]
        out.update({root + "en", root + "t", root + "de", root + "den",
                    root + "d", root + "end", root + "ende"})
    if term.endswith("elijk") and len(term) > 6:
        out.add(term[:-5] + "lijk")
    if term.endswith("lijk") and len(term) > 5:
        out.add(term[:-4] + "elijk")
    if term.endswith("en") and len(term) > 3:
        root = term[:-2]
        out.update({root, root + "t", root + "de", root + "den", root + "d",
                    "ge" + root + "d", "ge" + root + "t", root + "end",
                    root + "ende"})
    if term.endswith("e") and len(term) > 2:
        root = term[:-1]
        out.update({root + "en", root + "enen", root + "er", root + "ste"})
    if term.startswith("ge") and len(term) > 4:
        out.add(term[2:])
    return frozenset(out)


def match_token(word: str, term_variants: frozenset[str]) -> bool:
    """Return whether a translation token realises a definition term."""
    lower = fold(word)
    if lower in term_variants:
        return True

    # Dezelfde / hetzelfde / diezelfde / datzelfde.
    for prefix in ARTICLE_PREFIXES:
        if lower.startswith(prefix) and len(lower) > len(prefix) + 2:
            if lower[len(prefix):] in term_variants:
                return True

    # Parts of hyphenated tokens (e.g. "niet-goed").
    for part in re.split(r"[-'’]", lower):
        if part and part in term_variants:
            return True
    return False


def find_definition(term: str, words: List[str]) -> Tuple[str, int] | None:
    """Find the first translation span realising a definition term.

    Returns ``(surface, word_position)`` or ``None``.  For multi-word
    definitions the surface is the contiguous phrase, or the last content word
    in the all-words fallback.
    """
    term = fold(term.strip())
    parts = term.split()
    if not parts:
        return None

    if len(parts) == 1:
        part_variants = variants(term)
        for position, word in enumerate(words):
            if match_token(word, part_variants):
                return word, position
        return None

    # Contiguous phrase.
    for start in range(len(words) - len(parts) + 1):
        for offset, part in enumerate(parts):
            word = words[start + offset]
            if part in STOPWORDS:
                matched = fold(word) == part
            else:
                matched = match_token(word, variants(part))
            if not matched:
                break
        else:
            return " ".join(words[start:start + len(parts)]), start

    # Fallback: all content words occur somewhere in the sentence.
    last_hit: Tuple[str, int] | None = None
    for part in parts:
        if part in STOPWORDS:
            if not any(fold(word) == part for word in words):
                return None
            continue
        hit = next(
            ((word, position) for position, word in enumerate(words)
             if match_token(word, variants(part))),
            None,
        )
        if hit is None:
            return None
        last_hit = hit
    return last_hit


def glossary_definitions(entry: dict) -> List[str]:
    """Return the ordered Dutch definitions of a glossary entry.

    Current glossary files store a ``definitions`` list; older files store a
    comma-separated ``translation`` string, which is split on commas.
    """
    value = entry.get("definitions")
    if isinstance(value, list):
        return [str(part).strip() for part in value if str(part).strip()]
    legacy = entry.get("translation", "")
    return [part.strip() for part in str(legacy).split(",") if part.strip()]


def find_definition_in_text(definitions: List[str], text: str) -> Tuple[int, str] | None:
    """Return ``(definition_index, surface)`` for the first matching rendering."""
    words = WORD_RE.findall(text)
    for index, term in enumerate(definitions, start=1):
        hit = find_definition(term, words)
        if hit is not None:
            return index, hit[0]
    return None


def load_translations(run_dir: Path, translation_dir: Path | None = None) -> dict[str, str]:
    """Load ``id -> translation`` from the run's translation files."""
    directory = translation_dir or (run_dir / TRANSLATION_DIR_NAME)
    translations: dict[str, str] = {}
    for path in sorted(directory.glob("*.json")):
        with path.open("r", encoding="utf-8") as handle:
            payload = json.load(handle)
        for item in payload.get("translations", []):
            identifier = str(item["id"])
            if identifier in translations:
                raise ValueError(f"duplicate translation id {identifier} in {path}")
            translations[identifier] = item["translation"]
    if not translations:
        raise ValueError(f"no translations found in {directory}")
    return translations


def load_glossary_rows(run_dir: Path, glossary_dir: Path | None = None) -> List[Tuple[int, dict]]:
    """Load ``(batch, row)`` pairs from the run's glossary files."""
    directory = glossary_dir or (run_dir / GLOSSARY_DIR_NAME)
    rows: List[Tuple[int, dict]] = []
    seen: set[str] = set()
    # Every JSON file in 25_glossary is a glossary batch, regardless of tag
    # (batch_input.py names them batch<N>_<tag>.json).
    for path in sorted(directory.glob("*.json")):
        match = BATCH_RE.search(path.name)
        if not match:
            continue
        batch = int(match.group(1))
        with path.open("r", encoding="utf-8") as handle:
            payload = json.load(handle)
        for row in payload:
            identifier = str(row["id"])
            if identifier in seen:
                raise ValueError(f"duplicate glossary id {identifier} in {path}")
            seen.add(identifier)
            rows.append((batch, row))
    if not rows:
        raise ValueError(f"no glossary rows found in {directory}")
    rows.sort(key=lambda item: int(item[1]["id"]))
    return rows


def build_inventory(
    run_dir: Path,
    glossary_dir: Path | None = None,
    translation_dir: Path | None = None,
) -> Tuple[List[List[str]], dict]:
    """Build the inventory rows and summary statistics."""
    translations = load_translations(run_dir, translation_dir)
    glossary_rows = load_glossary_rows(run_dir, glossary_dir)

    missing = [row["id"] for _, row in glossary_rows
               if str(row["id"]) not in translations]
    if missing:
        raise ValueError(f"missing translations for ids: {missing[:5]}")

    output: List[List[str]] = []
    index_counts: Counter[int] = Counter()
    sentences_with_entries = 0
    entry_count = 0

    for batch, row in glossary_rows:
        entries = row.get("glossary", [])
        if entries:
            sentences_with_entries += 1
        sentence_id = str(row["id"])
        text = translations[sentence_id]
        for entry in entries:
            entry_count += 1
            definitions = glossary_definitions(entry)
            hit = find_definition_in_text(definitions, text)
            if hit is None:
                definition_index, dutch_word = 0, ""
            else:
                definition_index, dutch_word = hit
            index_counts[definition_index] += 1
            output.append([
                sentence_id,
                str(batch),
                entry.get("source", ""),
                entry.get("lemma", ""),
                ", ".join(definitions),
                str(len(definitions)),
                dutch_word,
                str(definition_index),
            ])

    summary = {
        "sentences": len(glossary_rows),
        "sentences_with_glossary": sentences_with_entries,
        "entries": entry_count,
        "matched": entry_count - index_counts.get(0, 0),
        "unmatched": index_counts.get(0, 0),
        "index_counts": dict(sorted(index_counts.items())),
    }
    return output, summary


def write_csv(path: Path, rows: Iterable[List[str]]) -> None:
    """Write the inventory to ``path`` as UTF-8 CSV."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow([
            "sentence_id",
            "batch",
            "source",
            "lemma",
            "translation",
            "alternatives",
            "dutch_word",
            "definition_index",
        ])
        writer.writerows(rows)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Inventory glossary definitions and their use in translations"
    )
    parser.add_argument(
        "run_dir",
        nargs="?",
        default="run-glossary",
        help="run directory containing 25_glossary/ and 30_translation/",
    )
    parser.add_argument(
        "-o",
        "--output",
        help=f"output CSV (default: <run-dir>/{OUTPUT_FILE_NAME})",
    )
    parser.add_argument(
        "--glossary-dir",
        help=f"glossary directory (default: <run-dir>/{GLOSSARY_DIR_NAME})",
    )
    parser.add_argument(
        "--translation-dir",
        help=f"translation directory (default: <run-dir>/{TRANSLATION_DIR_NAME})",
    )
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")

    run_dir = Path(args.run_dir).resolve()
    output_path = (
        Path(args.output).resolve()
        if args.output
        else run_dir / OUTPUT_FILE_NAME
    )

    rows, summary = build_inventory(
        run_dir,
        Path(args.glossary_dir) if args.glossary_dir else None,
        Path(args.translation_dir) if args.translation_dir else None,
    )
    write_csv(output_path, rows)

    logger.info("Sentences: %d (%d with glossary entries)",
                summary["sentences"], summary["sentences_with_glossary"])
    logger.info("Glossary entries: %d", summary["entries"])
    logger.info("Matched a proposed definition: %d (%.1f%%)",
                summary["matched"],
                100 * summary["matched"] / summary["entries"] if summary["entries"] else 0)
    logger.info("No proposed definition matched (index 0): %d (%.1f%%)",
                summary["unmatched"],
                100 * summary["unmatched"] / summary["entries"] if summary["entries"] else 0)
    logger.info("Definition index counts: %s", summary["index_counts"])
    logger.info("Written: %s", output_path)


if __name__ == "__main__":
    main()

