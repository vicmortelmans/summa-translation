#!/usr/bin/env python3
"""Inventory how the glossary definitions are applied in a translation run.

For every sentence in a run and every entry in that sentence's glossary, one CSV
row is written with the glossary fields and the Dutch word from the translation
that matches one of the entry's proposed Dutch definitions.

Expected run layout (as produced by ``batch_workflow.sh``)::

    <run-dir>/25_glossary/batch<N>_glossary.json
    <run-dir>/30_translation/batch<N>_glossary.json

Glossary files are lists of objects with ``id``, ``source`` and
``glossary``; each glossary entry currently has ``definitions`` (a list of
Dutch renderings), while older runs store a comma-separated ``translation``
string.  Both shapes are accepted.  Translation files contain
``{"translations": [{id, translation}]}``.

Matching is surface-based and deliberately conservative:

- the entry's definitions are the alternative Dutch renderings (the legacy
  comma-separated string is split on commas);
- a translation token matches a definition when it is the same word or a
  regular/irregular inflection (including Dutch spelling changes such as
  ``daad`` -> ``daden`` and ``geheel`` -> ``gehele``);
- compounds with a preceding article (``dezelfde``, ``hetzelfde``) and the parts
  of hyphenated tokens are also considered;
- multi-word definitions are matched as a contiguous phrase, or, as a fallback,
  when all their content words occur somewhere in the sentence.

The first definition (in glossary order) that matches wins, which mirrors the
first-definition bias of ``prompts/translate.txt``.  If none matches, the Dutch
word is left empty and the definition index is 0 ("another rendering is used").

Output columns: ``sentence_id`` (the ``id`` from the JSON files),
``batch``, ``source``, ``lemma``, ``translation`` (the definitions joined with
``", "``), ``alternatives`` (number of definitions), ``dutch_word`` and
``definition_index``.

Usage::

    ./env/bin/python glossary_application_inventory.py run-glossary

Output defaults to ``<run-dir>/glossary-application-inventory.csv``.
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
import re
import unicodedata
from collections import Counter
from functools import lru_cache
from pathlib import Path
from typing import Iterable, List, Tuple

GLOSSARY_DIR_NAME = "25_glossary"
TRANSLATION_DIR_NAME = "30_translation"
OUTPUT_FILE_NAME = "glossary-application-inventory.csv"
BATCH_RE = re.compile(r"batch(\d+)_")
WORD_RE = re.compile(r"[^\W\d_]+(?:[-'’][^\W\d_]+)*", re.UNICODE)

logger = logging.getLogger(__name__)

